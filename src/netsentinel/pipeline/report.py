# Writes the markdown results report from the metrics of each run.

import pandas as pd

RUN_TITLES = {
    "full": "NSL-KDD - full profile (40 features)",
    "live": "NSL-KDD - live profile (28 header features)",
    "cicids2017_random": "CIC-IDS2017 - random split",
    "cicids2017_temporal": "CIC-IDS2017 - temporal split (train Mon-Wed, test Thu-Fri)",
}


def pct(x):
    return f"{x * 100:.2f}%"


def run_section(res):
    meta = res["metadata"]
    lines = [
        f"## {RUN_TITLES.get(res['profile'], res['profile'])}",
        "",
        f"- classifier: **{meta['classifier']}**",
        f"- anomaly detector: **{meta['detector']}** (threshold at percentile {meta['threshold_percentile']})",
        f"- train rows: {meta['n_train']:,}, validation rows: {meta['n_validation']:,}, "
        f"columns after encoding: {meta['n_encoded_features']}",
        f"- classes seen in training: {', '.join(meta.get('train_classes', []))}",
        "",
        "### Classifiers (validation set)",
        "",
        pd.DataFrame(res["validation"]["classifier_comparison"]).T.to_markdown(),
        "",
        "### Anomaly detectors (validation set)",
        "",
        pd.DataFrame(res["validation"]["detector_comparison"]).T.to_markdown(),
        "",
    ]

    for split, m in res["test"].items():
        rows = {}
        for mode in ("classifier_only", "anomaly_only", "hybrid"):
            rows[mode] = {
                "Detection Rate": pct(m[mode]["detection_rate"]),
                "False Alarm Rate": pct(m[mode]["false_alarm_rate"]),
                "Precision": pct(m[mode]["precision"]),
                "F1": f"{m[mode]['f1']:.4f}",
                "Accuracy": pct(m[mode]["accuracy"]),
            }
        lines += [
            f"### Test set: {split} ({m['n_samples']:,} rows)",
            "",
            pd.DataFrame(rows).T.to_markdown(),
            "",
            f"- macro-F1 (multi-class): **{m['multiclass']['f1_macro']:.4f}**",
            "",
            "Detection rate per category (classifier only -> hybrid):",
            "",
        ]
        by_cat = m["detection_rate_by_category"]
        for cat, val in by_cat["classifier_only"].items():
            if cat != "normal":
                lines.append(f"- {cat}: {pct(val)} -> **{pct(by_cat['hybrid'][cat])}**")

        if "novel_attacks" in m:
            n = m["novel_attacks"]
            lines += [
                "",
                f"**Attacks not seen in training ({n['n_samples']:,} rows):**",
                "",
                "| mode | detection rate |",
                "|---|---|",
                f"| classifier only | {pct(n['classifier_only_dr'])} |",
                f"| anomaly only | {pct(n['anomaly_only_dr'])} |",
                f"| **hybrid** | **{pct(n['hybrid_dr'])}** |",
                "",
                f"types: {', '.join(n['attack_types'])}",
            ]
        if m.get("threshold_sensitivity"):
            sens = pd.DataFrame(m["threshold_sensitivity"]).set_index("percentile")
            sens = sens[["detection_rate", "false_alarm_rate", "precision", "f1", "novel_dr"]]
            lines += ["", "**Hybrid at other thresholds:**", "", sens.to_markdown(), ""]

        tag = split.replace("+", "plus")
        lines += ["", f"![confusion](./{res['profile']}/figures/confusion_{tag}.png)",
                  f"![roc](./{res['profile']}/figures/roc_{tag}.png)", ""]

    top = list(res["feature_importance"].items())[:10]
    lines += ["### Top 10 features (permutation importance)", ""]
    lines += [f"{i}. `{f}` {v:.4f}" for i, (f, v) in enumerate(top, 1)]
    lines += ["", f"![importance](./{res['profile']}/figures/feature_importance.png)", ""]
    return lines


def write_report(cfg, results, filename, title):
    lines = [f"# {title}", "", "Generated by `netsentinel train`.", ""]
    for res in results.values():
        lines += run_section(res)
    path = cfg.paths.reports_dir / filename
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
